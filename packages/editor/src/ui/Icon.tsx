export function Icon({
  name,
  size = 14,
  className,
  style,
  strokeWidth = 1.75,
  title,
}: {
  name: string | undefined;
  size?: number;
  className?: string;
  style?: CSSProperties;
  strokeWidth?: number;
  title?: string;
}) {
  const C = (name && ICONS[name]) || Circle;
  return (
    <C
      size={size}
      strokeWidth={strokeWidth}
      className={`icon ${className ?? ''}`}
      style={style}
      aria-hidden={title ? undefined : true}
      aria-label={title}
    />
  );
}
